//! Classified records for explicitly instrumented function calls.

use std::cell::RefCell;
use std::io;
use std::marker::PhantomData;
use std::path::Path;
use std::rc::Rc;
use std::sync::atomic::Ordering;
use std::sync::{Arc, Weak};
use std::time::Instant;

use serde_json::{Value, json};

use super::{ActiveTransition, Component, Level, Session, SessionState, timestamp_unix_ms};

thread_local! {
    static ACTIVE_CALLS: RefCell<Vec<(Weak<SessionState>, u64)>> = const { RefCell::new(Vec::new()) };
}

/// A value explicitly classified at an instrumentation boundary.
///
/// `Data` may contain sensitive or unclassified information and is only
/// written at the trace level. Known secrets must use `Secret`; that variant
/// accepts no secret value. A secret embedded in arbitrary `Data` cannot be
/// identified automatically.
pub enum TraceValue {
    /// A value representable without truncation as JSON.
    Data(Value),
    /// A known secret, excluded without accepting its contents.
    Secret,
    /// A value that cannot be captured at this boundary.
    Omitted(TraceOmission),
}

/// Reason a trace value is unavailable.
#[derive(Clone, Copy)]
pub enum TraceOmission {
    /// The value's type is not yet representable.
    UnsupportedType,
    /// The value belongs to code generated by a macro.
    GeneratedCode,
    /// The value is internal to an external component.
    ExternalComponent,
}

/// Encodes parsed TOML while omitting values under recognized secret keys.
///
/// The remaining values retain explicit TOML type tags. This protects values
/// only when their keys identify them as secrets; arbitrary strings are kept.
#[must_use]
pub fn trace_toml_value(value: &toml::Value) -> TraceValue {
    TraceValue::Data(toml_value_json(value))
}

/// Encodes a TOML table with recursive secret-key redaction.
#[must_use]
pub fn trace_toml_table(table: &toml::Table) -> TraceValue {
    TraceValue::Data(toml_table_json(table))
}

/// Encodes an optional TOML value with recursive secret-key redaction.
#[must_use]
pub fn trace_optional_toml_value(value: Option<&toml::Value>) -> TraceValue {
    value
        .map(trace_toml_value)
        .unwrap_or(TraceValue::Data(Value::Null))
}

/// Encodes JSON with recursive redaction of recognized secret keys.
///
/// Ordinary values remain structured JSON. Strings also redact recognizable
/// secret assignments, using the same key classifier as TOML tracing.
#[must_use]
pub fn trace_json_value(value: &Value) -> TraceValue {
    TraceValue::Data(json_value_redacted(value))
}

fn json_value_redacted(value: &Value) -> Value {
    match value {
        Value::Array(values) => Value::Array(values.iter().map(json_value_redacted).collect()),
        Value::Object(values) => Value::Object(
            values
                .iter()
                .map(|(key, value)| {
                    let value = if is_secret_key(key) {
                        TraceValue::Secret.to_json()
                    } else {
                        json_value_redacted(value)
                    };
                    (key.clone(), value)
                })
                .collect(),
        ),
        Value::String(value) => Value::String(redact_secret_assignments(value)),
        value => value.clone(),
    }
}

/// Keeps ordinary diagnostic text while redacting obvious secret assignments.
#[must_use]
pub fn trace_sensitive_text(value: &str) -> TraceValue {
    TraceValue::Data(
        json!({"format":"text_redacted_known_secret_assignments","value":redact_secret_assignments(value)}),
    )
}

/// Redacts recognizable secret assignments from a text representation.
#[must_use]
pub fn redact_secret_assignments(value: &str) -> String {
    let xml_redacted = redact_xml_secret_values(value);
    let value = xml_redacted.as_str();
    let bytes = value.as_bytes();
    let mut ranges = Vec::new();
    let mut index = 0;
    while index < bytes.len() {
        let (key_start, key_end, mut separator, json_quoted_key) = match bytes[index] {
            b'"' | b'\'' => {
                let quote = bytes[index];
                let start = index + 1;
                let mut end = start;
                while end < bytes.len() && bytes[end] != quote {
                    if bytes[end] == b'\\' {
                        end = (end + 2).min(bytes.len());
                    } else {
                        end += 1;
                    }
                }
                if end == bytes.len() {
                    index += 1;
                    continue;
                }
                let separator = end + 1;
                let mut delimiter = separator;
                while matches!(bytes.get(delimiter), Some(b' ' | b'\t' | b'\r')) {
                    delimiter += 1;
                }
                let mut crossed_line_break = false;
                if quote == b'"' {
                    while bytes.get(delimiter) == Some(&b'\n') {
                        crossed_line_break = true;
                        delimiter += 1;
                        while matches!(bytes.get(delimiter), Some(b' ' | b'\t' | b'\r')) {
                            delimiter += 1;
                        }
                    }
                }
                if !matches!(bytes.get(delimiter), Some(b'=' | b':')) {
                    index += 1;
                    continue;
                }
                if crossed_line_break && bytes.get(delimiter) != Some(&b':') {
                    index += 1;
                    continue;
                }
                index = separator;
                (start, end, delimiter, quote == b'"')
            }
            byte if is_key_byte(byte) && (index == 0 || !is_key_byte(bytes[index - 1])) => {
                let start = index;
                while index < bytes.len() && is_key_byte(bytes[index]) {
                    index += 1;
                }
                (start, index, index, false)
            }
            _ => {
                index += 1;
                continue;
            }
        };
        let key = &value[key_start..key_end];
        let secret_key = is_secret_key(key)
            || (json_quoted_key
                && key.contains('\\')
                && serde_json::from_str::<String>(&value[key_start - 1..key_end + 1])
                    .is_ok_and(|decoded| is_secret_key(&decoded)));
        if !secret_key {
            continue;
        }
        while matches!(bytes.get(separator), Some(b' ' | b'\t' | b'\r')) {
            separator += 1;
        }
        let Some(&separator_byte @ (b'=' | b':')) = bytes.get(separator) else {
            continue;
        };
        let mut value_start = separator + 1;
        while matches!(bytes.get(value_start), Some(b' ' | b'\t' | b'\r'))
            || (separator_byte == b':' && matches!(bytes.get(value_start), Some(b'\n')))
        {
            value_start += 1;
        }
        if let Some(value_end) = secret_assignment_end(value, value_start) {
            ranges.push(value_start..value_end);
            index = value_end.max(index + 1);
        }
    }
    let mut redacted = value.to_owned();
    for range in ranges.into_iter().rev() {
        redacted.replace_range(range, "[secret_omitted]");
    }
    redacted
}

fn redact_xml_secret_values(value: &str) -> String {
    let mut ranges = Vec::new();
    let mut search_from = 0;
    while let Some(key_offset) = value[search_from..].find("<key>") {
        let key_start = search_from + key_offset + "<key>".len();
        let Some(key_length) = value[key_start..].find("</key>") else {
            break;
        };
        let key_end = key_start + key_length;
        let element_start = key_end + "</key>".len();
        search_from = element_start;
        if !is_secret_key(value[key_start..key_end].trim()) {
            continue;
        }
        let mut value_start = element_start;
        while value
            .as_bytes()
            .get(value_start)
            .is_some_and(u8::is_ascii_whitespace)
        {
            value_start += 1;
        }
        if let Some(value_end) = xml_value_element_end(value, value_start) {
            ranges.push(value_start..value_end);
            search_from = value_end;
        }
    }
    let mut redacted = value.to_owned();
    for range in ranges.into_iter().rev() {
        redacted.replace_range(range, "[secret_omitted]");
    }
    redacted
}

fn xml_value_element_end(value: &str, start: usize) -> Option<usize> {
    let bytes = value.as_bytes();
    let opening_end = value[start..].find('>')? + start + 1;
    let opening = &value[start..opening_end];
    let name = opening
        .strip_prefix('<')?
        .strip_suffix('>')?
        .trim_end_matches('/');
    if !matches!(
        name,
        "string" | "integer" | "real" | "date" | "data" | "array" | "dict"
    ) {
        return None;
    }
    let closing = format!("</{name}>");
    if matches!(name, "array" | "dict") {
        let mut depth = 1_usize;
        let mut cursor = opening_end;
        while cursor < bytes.len() {
            let next_open = value[cursor..].find(opening).map(|offset| offset + cursor);
            let next_close = value[cursor..].find(&closing).map(|offset| offset + cursor);
            match (next_open, next_close) {
                (_, Some(close)) if next_open.is_none_or(|open| close < open) => {
                    depth -= 1;
                    let end = close + closing.len();
                    if depth == 0 {
                        return Some(end);
                    }
                    cursor = end;
                }
                (Some(open), _) => {
                    depth += 1;
                    cursor = open + opening.len();
                }
                _ => return None,
            }
        }
        None
    } else {
        value[start..]
            .find(&closing)
            .map(|offset| offset + start + closing.len())
    }
}

fn is_key_byte(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || matches!(byte, b'_' | b'-')
}

fn secret_assignment_end(value: &str, start: usize) -> Option<usize> {
    let bytes = value.as_bytes();
    let first = *bytes.get(start)?;
    if first == b'\\' && matches!(bytes.get(start + 1), Some(b'"' | b'\'')) {
        return Some(
            value[start..]
                .find("\\n")
                .map(|end| start + end)
                .unwrap_or(bytes.len()),
        );
    }
    if first == b'\'' || first == b'"' {
        let quote_end = if bytes.get(start..start + 3) == Some(&[first, first, first]) {
            let marker = [first, first, first];
            value[start + 3..]
                .find(std::str::from_utf8(&marker).ok()?)
                .map(|end| end + start + 6)
                .unwrap_or(bytes.len())
        } else {
            let mut cursor = start + 1;
            while cursor < bytes.len() {
                if bytes[cursor] == b'\\' {
                    cursor = (cursor + 2).min(bytes.len());
                } else if bytes[cursor] == first {
                    return Some(cursor + 1);
                } else {
                    cursor += 1;
                }
            }
            return Some(bytes.len());
        };
        return Some(quote_end);
    }

    let mut stack = Vec::new();
    let mut quote = None;
    let mut cursor = start;
    while cursor < bytes.len() {
        let byte = bytes[cursor];
        if let Some(delimiter) = quote {
            if byte == b'\\' {
                cursor = (cursor + 2).min(bytes.len());
                continue;
            }
            if byte == delimiter {
                quote = None;
            }
        } else if (byte == b'\'' || byte == b'"')
            && stack.is_empty()
            && matches!(
                bytes.get(cursor + 1),
                None | Some(b',' | b';' | b'\n' | b'\r' | b']' | b'}' | b')' | b' ' | b'\t')
            )
        {
            // A secret assignment inside a quoted Debug string has no quote
            // at `value_start`; stop before the string's closing quote instead
            // of treating it as the start of a new quoted value.
            return Some(cursor);
        } else if byte == b'\'' || byte == b'"' {
            quote = Some(byte);
        } else if byte == b'\\' {
            cursor = (cursor + 2).min(bytes.len());
            continue;
        } else if matches!(byte, b'(' | b'[' | b'{') {
            stack.push(byte);
        } else if matches!(byte, b')' | b']' | b'}') {
            if stack.is_empty() {
                break;
            }
            stack.pop();
            if stack.is_empty() {
                cursor += 1;
                break;
            }
        } else if stack.is_empty() && matches!(byte, b',' | b';' | b'\n') {
            break;
        }
        cursor += 1;
    }
    while cursor > start && bytes[cursor - 1].is_ascii_whitespace() {
        cursor -= 1;
    }
    Some(cursor)
}

fn toml_value_json(value: &toml::Value) -> Value {
    match value {
        toml::Value::String(value) => {
            json!({"type":"string","value":redact_secret_assignments(value)})
        }
        toml::Value::Integer(value) => json!({"type":"integer","value":value}),
        toml::Value::Float(value) => json!({"type":"float","value":value.to_string()}),
        toml::Value::Boolean(value) => json!({"type":"boolean","value":value}),
        toml::Value::Datetime(value) => json!({"type":"datetime","value":value.to_string()}),
        toml::Value::Array(values) => {
            json!({"type":"array","value":values.iter().map(toml_value_json).collect::<Vec<_>>()})
        }
        toml::Value::Table(table) => toml_table_json(table),
    }
}

fn toml_table_json(table: &toml::Table) -> Value {
    Value::Object(
        table
            .iter()
            .map(|(key, value)| {
                let value = if is_secret_key(key) {
                    TraceValue::Secret.to_json()
                } else {
                    toml_value_json(value)
                };
                (key.clone(), value)
            })
            .collect(),
    )
}

fn is_secret_key(key: &str) -> bool {
    let normalized = key
        .chars()
        .filter(char::is_ascii_alphanumeric)
        .flat_map(char::to_lowercase)
        .collect::<String>();
    [
        "password",
        "passwd",
        "passphrase",
        "passcode",
        "token",
        "sessiontoken",
        "secret",
        "credential",
        "apikey",
        "accesskey",
        "refreshkey",
        "authkey",
        "privatekey",
        "authorization",
        "bearer",
        "cookie",
        "signingkey",
        "encryptionkey",
    ]
    .iter()
    .any(|marker| normalized.contains(marker))
}

/// Constructs and serializes classified trace values.
impl TraceValue {
    /// Converts a value to JSON; the caller must ensure conversion is lossless.
    /// For example, non-finite floating-point values require another encoding.
    #[must_use]
    pub fn data(value: impl Into<Value>) -> Self {
        Self::Data(value.into())
    }

    /// Represents a collection of named, independently classified fields.
    #[must_use]
    pub fn record(fields: &[TraceField]) -> Self {
        Self::Data(Value::Array(
            fields
                .iter()
                .map(|field| json!({"name": field.name, "content": field.value.to_json()}))
                .collect(),
        ))
    }

    /// Represents a path without losing platform-native non-Unicode data.
    ///
    /// If the lossy display form contains a recognized secret assignment, the
    /// path is omitted instead of storing either the secret or an altered path.
    #[must_use]
    pub fn path(path: &Path) -> Self {
        let display = path.display().to_string();
        if redact_secret_assignments(&display) != display {
            return Self::Secret;
        }
        if let Some(text) = path.to_str() {
            return Self::Data(json!({"encoding": "utf8", "value": text}));
        }
        #[cfg(unix)]
        {
            use std::os::unix::ffi::OsStrExt;
            return Self::Data(
                json!({"encoding": "unix_bytes", "value": path.as_os_str().as_bytes()}),
            );
        }
        #[cfg(windows)]
        {
            use std::os::windows::ffi::OsStrExt;
            return Self::Data(
                json!({"encoding": "windows_utf16", "value": path.as_os_str().encode_wide().collect::<Vec<_>>()}),
            );
        }
        #[allow(unreachable_code)]
        Self::Omitted(TraceOmission::UnsupportedType)
    }

    /// Returns a classified JSON representation, omitting identified secrets.
    #[must_use]
    pub fn to_json(&self) -> Value {
        match self {
            Self::Data(value) => json!({"kind": "data", "value": value}),
            Self::Secret => json!({"kind": "secret_omitted"}),
            Self::Omitted(reason) => json!({"kind": "omitted", "reason": reason.as_str()}),
        }
    }
}

/// Maps omission reasons to stable log identifiers.
impl TraceOmission {
    const fn as_str(self) -> &'static str {
        match self {
            Self::UnsupportedType => "unsupported_type",
            Self::GeneratedCode => "generated_code",
            Self::ExternalComponent => "external_component",
        }
    }
}

/// A named argument of a function call.
pub struct TraceField {
    name: &'static str,
    value: TraceValue,
}

/// A session and causal parent that can be explicitly passed to a worker.
#[derive(Clone)]
pub struct TraceLink {
    session: Session,
    parent_id: Option<u64>,
    operation_id: Option<u64>,
    lease: Option<Arc<LinkLease>>,
}

struct LinkLease {
    session: Session,
    id: u64,
}

/// Releases the session's active worker link when its last lease is dropped.
impl Drop for LinkLease {
    fn drop(&mut self) {
        let _ = self.session.write_active_record(
            &json!({"type": "worker_link_released", "timestamp_unix_ms": timestamp_unix_ms(), "link_id": self.id}),
            ActiveTransition::End(self.id),
        );
    }
}

struct ParentGuard {
    session: Weak<SessionState>,
    id: u64,
}

/// Restores the previous trace parent when a scope exits.
impl Drop for ParentGuard {
    fn drop(&mut self) {
        ACTIVE_CALLS.with(|active| {
            let mut active = active.borrow_mut();
            if let Some(index) = active
                .iter()
                .rposition(|(session, id)| *id == self.id && Weak::ptr_eq(session, &self.session))
            {
                active.remove(index);
            }
        });
    }
}

/// Propagates a trace parent and session into another thread.
impl TraceLink {
    /// Runs worker code with the linked session and parent call.
    pub fn scoped<R>(&self, action: impl FnOnce() -> R) -> R {
        let _lease = &self.lease;
        self.session.scoped_with_operation(self.operation_id, || {
            let _parent = self.parent_id.map(|id| {
                let session = Arc::downgrade(&self.session.state);
                ACTIVE_CALLS.with(|active| active.borrow_mut().push((session.clone(), id)));
                ParentGuard { session, id }
            });
            action()
        })
    }
}

/// Associates a field name with its classified value.
impl TraceField {
    /// Creates an argument with a static name and an explicitly classified value.
    #[must_use]
    pub const fn new(name: &'static str, value: TraceValue) -> Self {
        Self { name, value }
    }
}

/// Begins a trace in the current thread's session, if trace is enabled.
///
/// Arguments are constructed lazily. Write failures are remembered by the
/// session and must be surfaced by the owning frontend. A missing span can
/// therefore mean either tracing was disabled or a write failed.
#[must_use]
pub fn trace_current(
    component: Component,
    function: &'static str,
    arguments: impl FnOnce() -> Vec<TraceField>,
) -> Option<TraceSpan> {
    let session = Session::current()?;
    if !session.trace_enabled() {
        return None;
    }
    session
        .trace_call(component, function, &arguments())
        .ok()
        .flatten()
}

/// Creates trace spans associated with this session.
impl Session {
    /// Captures the current causal parent for explicit transfer to a worker.
    ///
    /// The session cannot finish until all clones of this link are dropped.
    /// A failure to record the link is retained by [`Self::has_failed`].
    #[must_use]
    pub fn trace_link(&self) -> TraceLink {
        let parent_id = ACTIVE_CALLS.with(|active| {
            active.borrow().iter().rev().find_map(|(session, parent)| {
                session
                    .upgrade()
                    .filter(|session| Arc::ptr_eq(session, &self.state))
                    .map(|_| *parent)
            })
        });
        let id = self.state.next_operation.fetch_add(1, Ordering::Relaxed);
        let lease = self.write_active_record(
            &json!({"type": "worker_link_created", "timestamp_unix_ms": timestamp_unix_ms(), "link_id": id}),
            ActiveTransition::Start(id),
        ).ok().map(|()| Arc::new(LinkLease { session: self.clone(), id }));
        TraceLink {
            session: self.clone(),
            parent_id,
            operation_id: super::context::current_operation_id(self),
            lease,
        }
    }

    /// Whether this session accepts detailed trace records.
    #[must_use]
    pub fn trace_enabled(&self) -> bool {
        self.state.level == Level::Trace
    }

    /// Starts a classified function trace, returning no span at lower levels.
    ///
    /// The function and argument names must be static code identifiers rather
    /// than user input. Callers should check [`Self::trace_enabled`] before
    /// preparing expensive argument values.
    ///
    /// # Errors
    ///
    /// Returns an error if the entry record cannot be written.
    pub fn trace_call(
        &self,
        component: Component,
        function: &'static str,
        arguments: &[TraceField],
    ) -> io::Result<Option<TraceSpan>> {
        if !self.trace_enabled() {
            return Ok(None);
        }
        let id = self.state.next_operation.fetch_add(1, Ordering::Relaxed);
        let parent_id = ACTIVE_CALLS.with(|active| {
            active.borrow().iter().rev().find_map(|(session, parent)| {
                session
                    .upgrade()
                    .filter(|session| Arc::ptr_eq(session, &self.state))
                    .map(|_| *parent)
            })
        });
        let arguments: Vec<Value> = arguments
            .iter()
            .map(|field| json!({"name": field.name, "content": field.value.to_json()}))
            .collect();
        self.write_active_record(
            &json!({
                "type": "function_enter",
                "timestamp_unix_ms": timestamp_unix_ms(),
                "component": component.as_str(),
                "function": function,
                "call_id": id,
                "parent_call_id": parent_id,
                "operation_id": super::context::current_operation_id(self),
                "arguments": arguments,
            }),
            ActiveTransition::Start(id),
        )?;
        ACTIVE_CALLS.with(|active| active.borrow_mut().push((Arc::downgrade(&self.state), id)));
        Ok(Some(TraceSpan {
            session: self.clone(),
            component,
            function,
            id,
            started: Instant::now(),
            finished: false,
            not_send: PhantomData,
        }))
    }
}

/// One entered function call; an unfinished drop records an explicit omission.
pub struct TraceSpan {
    session: Session,
    component: Component,
    function: &'static str,
    id: u64,
    started: Instant,
    finished: bool,
    // A span updates the thread-local call stack and cannot move to another thread.
    not_send: PhantomData<Rc<()>>,
}

/// Records a span's classified outcome and elapsed duration.
impl TraceSpan {
    /// Records the return value and ends the span.
    ///
    /// # Errors
    ///
    /// Returns an error if the return record cannot be written.
    pub fn finish(mut self, result: TraceValue) -> io::Result<()> {
        self.finished = true;
        self.write_exit("returned", result.to_json())
    }

    fn write_exit(&self, outcome: &'static str, result: Value) -> io::Result<()> {
        let elapsed = u64::try_from(self.started.elapsed().as_millis()).unwrap_or(u64::MAX);
        self.session.write_active_record(
            &json!({
                "type": "function_exit",
                "timestamp_unix_ms": timestamp_unix_ms(),
                "component": self.component.as_str(),
                "function": self.function,
                "call_id": self.id,
                "duration_ms": elapsed,
                "outcome": outcome,
                "result": result,
            }),
            ActiveTransition::End(self.id),
        )
    }
}

/// Marks a trace span unfinished if it is dropped without an outcome.
impl Drop for TraceSpan {
    fn drop(&mut self) {
        if !self.finished {
            let _ = self.write_exit(
                "unfinished",
                json!({"kind": "omitted", "reason": "unfinished_call"}),
            );
            self.session.state.failed.store(true, Ordering::Relaxed);
        }
        ACTIVE_CALLS.with(|active| {
            let mut active = active.borrow_mut();
            if let Some(index) = active.iter().rposition(|(session, id)| {
                *id == self.id
                    && session
                        .upgrade()
                        .is_some_and(|session| Arc::ptr_eq(&session, &self.session.state))
            }) {
                active.remove(index);
            }
        });
    }
}

