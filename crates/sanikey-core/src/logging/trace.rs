    #[test]
    fn explicit_link_preserves_parent_across_worker_threads() {
        let directory = std::env::temp_dir().join(format!(
            "sanikey-linked-trace-{}-{:?}",
            std::process::id(),
            std::thread::current().id()
        ));
        let (session, path) =
            Session::create_in_directory_with_level(&directory, Component::Core, Level::Trace)
                .unwrap();
        let operation = session
            .start_operation(Component::Core, super::super::Activity::Build)
            .unwrap();
        operation.scoped(|| {
            let outer = session
                .trace_call(Component::Core, "outer", &[])
                .unwrap()
                .unwrap();
            let link = session.trace_link();
            std::thread::spawn(move || {
                link.scoped(|| {
                    let current = Session::current().unwrap();
                    current
                        .trace_call(Component::Core, "worker", &[])
                        .unwrap()
                        .unwrap()
                        .finish(TraceValue::Data(json!(null)))
                        .unwrap();
                })
            })
            .join()
            .unwrap();
            outer.finish(TraceValue::Data(json!(null))).unwrap();
        });
        operation.finish(super::super::Outcome::Succeeded).unwrap();
        drop(session);
        let contents = fs::read_to_string(&path).unwrap();
        let entries: Vec<serde_json::Value> = contents
            .lines()
            .map(|line| serde_json::from_str(line).unwrap())
            .collect();
        let outer = entries
            .iter()
            .find(|entry| entry["type"] == "function_enter" && entry["function"] == "outer")
            .unwrap();
        let worker = entries
            .iter()
            .find(|entry| entry["type"] == "function_enter" && entry["function"] == "worker")
            .unwrap();
        assert_eq!(worker["parent_call_id"], outer["call_id"]);
        assert_eq!(worker["operation_id"], 1);
        assert_eq!(outer["operation_id"], 1);
        fs::remove_file(path).unwrap();
        fs::remove_dir(directory).unwrap();
    }

